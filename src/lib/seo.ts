import type { Metadata } from "next";
import { isIndexable, siteUrl } from "@/config/env";
import { site } from "@/config/site";
import { pranav } from "@/data/pranav";
import type { FaqItem, Service } from "@/types/content";

export function absoluteUrl(path = "/"): string {
  return `${siteUrl}${path.startsWith("/") ? path : `/${path}`}`;
}

interface PageMetaInput {
  title: string;
  description: string;
  /** Path without query string – used as the canonical URL. */
  path: string;
  /** Advertising landing pages and drafts are kept out of search results. */
  noindex?: boolean;
  /** Use the title as-is instead of applying the "· Aligned by Pranav" template. */
  absoluteTitle?: boolean;
  /** Set when the route has its own opengraph-image file (e.g. service pages). */
  ownSocialImage?: boolean;
}

/** Branded social image generated by src/app/opengraph-image.tsx. Service pages have their own. */
const defaultSocialImage = {
  url: "/opengraph-image",
  width: 1200,
  height: 630,
  alt: `${site.name} – personal consultations with Pranav Vibhute`,
};

/**
 * Per-page metadata with a canonical URL that ignores query strings, so ad
 * URLs with UTM parameters never create duplicate pages in search.
 */

export function pageMetadata({ title, description, path, noindex, absoluteTitle, ownSocialImage }: PageMetaInput): Metadata {
  const index = isIndexable && !noindex;
  const images = ownSocialImage ? undefined : [defaultSocialImage];
  return {
    title: absoluteTitle ? { absolute: title } : title,
    description,
    alternates: { canonical: path },
    openGraph: {
      type: "website",
      siteName: site.name,
      locale: "en",
      url: path,
      title: absoluteTitle ? title : `${title} · ${site.name}`,
      description,
      // The key must be absent (not undefined) for a route's own image file to apply.
      ...(images ? { images } : {}),
    },
    twitter: {
      card: "summary_large_image",
      title,
      description,
      ...(images ? { images: images.map((i) => i.url) } : {}),
    },
    robots: { index, follow: true },
  };
}

/* ------------------------------------------------------------------
   Structured data (JSON-LD). Only factual, confirmed fields are used:
   no address, ratings, price or opening hours until they are real.
   ------------------------------------------------------------------ */

type JsonLd = Record<string, unknown>;

const organizationId = `${siteUrl}/#organization`;
const personId = `${siteUrl}/#pranav`;

function sameAs(): string[] {
  return [site.social.instagram, site.social.facebook].filter((v): v is string => Boolean(v));
}

export function organizationJsonLd(): JsonLd {
  return {
    "@context": "https://schema.org",
    "@type": "ProfessionalService",
    "@id": organizationId,
    name: site.name,
    slogan: site.tagline,
    description: site.description,
    url: absoluteUrl("/"),
    logo: absoluteUrl("/icon.svg"),
    image: absoluteUrl("/opengraph-image"),
    areaServed: [
      { "@type": "Country", name: "India" },
      { "@type": "Place", name: "Europe" },
    ],
    knowsLanguage: "en",
    employee: { "@id": personId },
    ...(sameAs().length ? { sameAs: sameAs() } : {}),
    ...(site.contact.email ? { email: site.contact.email } : {}),
  };
}

export function personJsonLd(): JsonLd {
  return {
    "@context": "https://schema.org",
    "@type": "Person",
    "@id": personId,
    name: pranav.name,
    jobTitle: pranav.title,
    worksFor: { "@id": organizationId },
    url: absoluteUrl("/about"),
    ...(pranav.portrait ? { image: absoluteUrl(pranav.portrait.src) } : {}),
  };
}

export function serviceJsonLd(service: Service): JsonLd {
  return {
    "@context": "https://schema.org",
    "@type": "Service",
    name: service.title,
    serviceType: service.title,
    description: service.intro,
    url: absoluteUrl(`/services/${service.slug}`),
    provider: { "@id": organizationId },
    areaServed: [
      { "@type": "Country", name: "India" },
      { "@type": "Place", name: "Europe" },
    ],
  };
}

export function breadcrumbJsonLd(items: { name: string; path: string }[]): JsonLd {
  return {
    "@context": "https://schema.org",
    "@type": "BreadcrumbList",
    itemListElement: items.map((item, index) => ({
      "@type": "ListItem",
      position: index + 1,
      name: item.name,
      item: absoluteUrl(item.path),
    })),
  };
}

export function faqJsonLd(faqs: FaqItem[]): JsonLd {
  return {
    "@context": "https://schema.org",
    "@type": "FAQPage",
    mainEntity: faqs.map((faq) => ({
      "@type": "Question",
      name: faq.question,
      acceptedAnswer: { "@type": "Answer", text: faq.answer },
    })),
  };
}
