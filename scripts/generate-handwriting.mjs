/**
 * Generates single-stroke handwriting paths for the brand.
 *
 * Source: EMS Allure (SIL Open Font License), a single-line engraving font
 * derived from Allura, shipped in the `hersheytext` package. Each word becomes
 * ONE continuous SVG path (pen lifts become move-to commands), smoothed from
 * the font's polylines into Catmull–Rom curves, so it can be "written" on
 * screen with a single stroke-dashoffset animation and followed by a pen nib.
 *
 * usage: node scripts/generate-handwriting.mjs
 * output: src/components/brand/handwriting-data.ts
 */
import { readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";

const require = createRequire(import.meta.url);
const FONT = require.resolve("hersheytext/svg_fonts/EMSAllure.svg");
const WORDS = { aligned: "aligned", details: "details", a: "a" };

const src = readFileSync(FONT, "utf8");
const glyphs = {};
for (const m of src.matchAll(/<glyph\b([^>]*)\/?>/g)) {
  const attrs = m[1];
  const unicode = attrs.match(/unicode="([^"]*)"/)?.[1];
  if (unicode === undefined) continue;
  glyphs[unicode] = {
    adv: Number(attrs.match(/horiz-adv-x="([-\d.]+)"/)?.[1] ?? 500),
    d: attrs.match(/\sd="([^"]*)"/)?.[1] ?? "",
  };
}

/** Parses "M x y L x y …" into polylines of [x, y] points. */
function polylines(d, dx) {
  const lines = [];
  const tokens = d.trim().split(/\s+/);
  for (let i = 0; i < tokens.length; ) {
    const cmd = tokens[i++];
    const x = Number(tokens[i++]) + dx;
    const y = -Number(tokens[i++]); // font units are y-up; SVG is y-down
    if (cmd === "M") lines.push([[x, y]]);
    else lines.at(-1).push([x, y]);
  }
  return lines;
}

const r = (n) => Math.round(n * 10) / 10;

/** Catmull–Rom spline through the points, as cubic Béziers. */
function smooth(points) {
  if (points.length < 3) return `M${points.map(([x, y]) => `${r(x)} ${r(y)}`).join("L")}`;
  let d = `M${r(points[0][0])} ${r(points[0][1])}`;
  for (let i = 0; i < points.length - 1; i++) {
    const p0 = points[i - 1] ?? points[i];
    const p1 = points[i];
    const p2 = points[i + 1];
    const p3 = points[i + 2] ?? p2;
    const c1 = [p1[0] + (p2[0] - p0[0]) / 6, p1[1] + (p2[1] - p0[1]) / 6];
    const c2 = [p2[0] - (p3[0] - p1[0]) / 6, p2[1] - (p3[1] - p1[1]) / 6];
    d += `C${r(c1[0])} ${r(c1[1])} ${r(c2[0])} ${r(c2[1])} ${r(p2[0])} ${r(p2[1])}`;
  }
  return d;
}

const out = {};
for (const [key, text] of Object.entries(WORDS)) {
  let x = 0;
  const lines = [];
  for (const ch of text) {
    const g = glyphs[ch];
    if (!g) throw new Error(`Missing glyph "${ch}"`);
    if (g.d) lines.push(...polylines(g.d, x));
    x += g.adv;
  }
  const xs = lines.flat().map((p) => p[0]);
  const ys = lines.flat().map((p) => p[1]);
  const pad = 40;
  const box = [Math.min(...xs) - pad, Math.min(...ys) - pad, Math.max(...xs) - Math.min(...xs) + pad * 2, Math.max(...ys) - Math.min(...ys) + pad * 2];
  out[key] = { d: lines.map(smooth).join(""), viewBox: box.map(r).join(" ") };
}

const banner = "// GENERATED by scripts/generate-handwriting.mjs – do not edit by hand.\n// Strokes from EMS Allure (SIL Open Font License), via the hersheytext package.\n";
const metrics =
  "\n/** Font guide lines in the same units (y-down, baseline at 0). */\nexport const handwritingGuides = { ascender: -720, xHeight: -356, baseline: 0, descender: 416 } as const;\n";
writeFileSync(
  "src/components/brand/handwriting-data.ts",
  `${banner}\nexport const handwriting = ${JSON.stringify(out, null, 2)} as const;\n${metrics}`,
);
console.log("wrote src/components/brand/handwriting-data.ts", Object.keys(out));
